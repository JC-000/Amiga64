"""Host tests for the WB-measure floppy model (tools/s3probe/adf.py, wb_disk.py).

docs/WB_BOOT.md.  Every image here is generated by adf.build_adf: no test
reads the user's Workbench disks.  The model legs boot the pinned AROS ROM
with a synthetic bootable ADF and skip cleanly without the ROM cache or the
s3probe venv (tools/s3probe/setup_venv.sh).
"""
import glob
import json
import os
import struct
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "s3probe"))

import adf  # noqa: E402
import wb_disk  # noqa: E402

FILES = {
    "S/Startup-Sequence": b"Echo hello\n" * 70,          # 770 bytes: 2 OFS blocks
    "C/Tool": bytes(range(256)) * 5,
    "Empty": b"",
}
# move.l #$C0DEF00D,d7 ; bra.s *  -- the boot block the model legs run
BOOTCODE = bytes.fromhex("2E3CC0DEF00D60FE")


@pytest.mark.parametrize("ffs", [False, True])
def test_adf_roundtrip(ffs):
    img = adf.AdfImage.from_bytes(adf.build_adf(FILES, ffs=ffs, bootcode=BOOTCODE))
    assert img.ffs is ffs and img.bootable()
    assert img.volume_name() == "Synth"
    for path, content in FILES.items():
        k = img.lookup(path)
        assert k is not None and img.read_file(k) == content
    assert img.lookup("s/startup-SEQUENCE") == img.lookup("S/Startup-Sequence")
    assert img.lookup("S/Missing") is None
    listed = {p: size for p, size, _k in img.walk()}
    assert listed["C/"] is None and listed["C/Tool"] == 1280


@pytest.mark.parametrize("ffs", [False, True])
def test_patched_startup_is_in_memory_only(ffs):
    img = _image(ffs=ffs)
    before = img.data
    new = img.patched("S/Startup-Sequence", b"LoadWB\nEndCLI >NIL:\n")
    assert img.data == before                    # the original is untouched
    assert new.read_file(new.lookup("S/Startup-Sequence")) == b"LoadWB\nEndCLI >NIL:\n"
    assert new.read_file(new.lookup("C/Tool")) == FILES["C/Tool"]
    hk = new.lookup("S/Startup-Sequence")
    assert sum(struct.unpack(">128I", new.block(hk))) & 0xFFFFFFFF == 0
    with pytest.raises(ValueError):
        img.patched("S/Startup-Sequence", b"x" * 2000)


def test_block_checksums_sum_to_zero():
    data = adf.build_adf(FILES)
    for k in (adf.ROOT, adf.ROOT + 2):
        b = data[k * 512:(k + 1) * 512]
        assert sum(struct.unpack(">128I", b)) & 0xFFFFFFFF == 0
    assert not adf.AdfImage.from_bytes(data).bootable()     # no boot code given
    boot = bytearray(adf.build_adf(FILES, bootcode=BOOTCODE))
    assert adf.AdfImage.from_bytes(bytes(boot)).bootable()
    boot[100] ^= 1
    assert not adf.AdfImage.from_bytes(bytes(boot)).bootable()


def test_hunk_kind():
    code = struct.pack(">6I", 0x3F3, 0, 1, 0, 0, 2) + struct.pack(">4I", 0x3E9, 2, 0x4E75, 0) \
        + struct.pack(">I", 0x3F2)
    bcpl = struct.pack(">6I", 0x3F3, 0, 1, 0, 0, 2) + struct.pack(">4I", 0x3E9, 2, 2, 0) \
        + struct.pack(">I", 0x3F2)
    assert adf.hunk_kind(code) == "c"
    assert adf.hunk_kind(bcpl) == "bcpl"
    assert adf.hunk_kind(b"Echo hi\n" * 8) == "data"


def _image(**kw):
    return adf.AdfImage.from_bytes(adf.build_adf(FILES, **kw))


def _decode(words, track):
    """A Python port of AROS td_decodebuffer_ados (trackdisk_hw.c): the
    checks the ROM applies, so the encoder is tested against them."""
    mask = 0x55555555

    def mfmlong(i):
        return ((words[i] << 16) | words[i + 1]) & mask

    out, i, first = {}, 0, True
    while len(out) < adf.SECTORS:
        if not first:
            while i < len(words) and words[i] != 0x4489:
                i += 1
        first = False
        while i < len(words) and words[i] == 0x4489:
            i += 1
        if i + 544 >= len(words):
            break
        nxt = i + 541
        chk = mfmlong(i) ^ mfmlong(i + 2)
        ident = (mfmlong(i) << 1) | mfmlong(i + 2)
        i += 4
        sec = (ident >> 8) & 0xFF
        if sec >= adf.SECTORS or ident >> 24 != 0xFF:
            continue
        for _ in range(4):
            chk ^= mfmlong(i) ^ mfmlong(i + 8)
            i += 2
        i += 8
        hsum = (mfmlong(i) << 1) | mfmlong(i + 2)
        i += 4
        if hsum != chk or (ident >> 16) & 0xFF != track:
            i = nxt
            continue
        dsum = (mfmlong(i) << 1) | mfmlong(i + 2)
        i += 4
        data = bytearray()
        for j in range(128):
            odd, even = mfmlong(i + 2 * j), mfmlong(i + 256 + 2 * j)
            dsum ^= odd ^ even
            data += struct.pack(">I", (odd << 1) | even)
        if dsum == 0:
            out[sec] = bytes(data)
        i = nxt
    return out


@pytest.mark.parametrize("track", [0, 1, 80, 159])
def test_mfm_track_decodes_like_aros(track):
    img = _image()
    raw = wb_disk.mfm_track(img, track, wb_disk.DSK_WORDS_DEFAULT)
    words = list(struct.unpack(f">{len(raw) // 2}H", raw))
    assert words[0] == 0x4489                    # WORDSYNC: after the first sync
    got = _decode(words, track)
    want = img.track(track)
    assert sorted(got) == list(range(adf.SECTORS))
    assert b"".join(got[s] for s in range(adf.SECTORS)) == want


def test_mfm_clock_bits_are_legal():
    raw = wb_disk.mfm_track(_image(), 80, 6000)
    bits = "".join(f"{w:016b}" for w in struct.unpack(">6000H", raw))
    assert "11" not in bits                      # MFM never has adjacent ones
    assert "00000" not in bits                   # ... nor more than three zeros


def test_mfm_teeth_bad_checksum_and_wrong_track():
    img = _image()
    raw = bytearray(wb_disk.mfm_track(img, 80, wb_disk.DSK_WORDS_DEFAULT))
    raw[2 * 600] ^= 0x01                         # a data bit of sector 1
    words = list(struct.unpack(f">{len(raw) // 2}H", bytes(raw)))
    assert 1 not in _decode(words, 80)
    good = list(struct.unpack(">7000H", wb_disk.mfm_track(img, 80, 7000)))
    assert _decode(good, 81) == {}               # header names track 80


def test_floppy_lines():
    fl = wb_disk.Floppy(_image())
    assert fl.pra_bits() == 0x3C                 # nothing selected: all high
    fl.write_prb(0xFF & ~0x80)                   # motor on, not selected yet
    fl.write_prb(0xFF & ~0x80 & ~0x08)           # select DF0: motor latched on
    assert fl.selected and fl.motor
    b = fl.pra_bits()
    assert not b & 0x20 and not b & 0x10         # ready, track 0
    assert not b & 0x08 and not b & 0x04         # protected, /CHNG still low
    v = 0xFF & ~0x80 & ~0x08 & ~0x02             # direction in
    fl.write_prb(v & ~0x01)
    fl.write_prb(v)                              # step pulse (rising edge)
    assert fl.cyl == 1 and fl.pra_bits() & 0x10 and fl.pra_bits() & 0x04
    fl.write_prb(v & ~0x04)                      # /SIDE low: upper head
    assert fl.track == 3
    fl.write_prb((v | 0x02) & ~0x01)
    fl.write_prb(v | 0x02)                       # step out
    assert fl.cyl == 0
    empty = wb_disk.Floppy(None)
    empty.write_prb(0xF7)
    empty.write_prb(0xF6)
    empty.write_prb(0xF7)
    assert not empty.pra_bits() & 0x04           # no disk: /CHNG stays low


class _Mem:
    def __init__(self):
        self.b = bytearray(0x10000)

    def r8(self, a):
        return self.b[a]

    def r16(self, a):
        return struct.unpack_from(">H", self.b, a)[0]

    def r32(self, a):
        return struct.unpack_from(">I", self.b, a)[0]

    def w8(self, a, v):
        self.b[a] = v

    def w32(self, a, v):
        struct.pack_into(">I", self.b, a, v)

    def w_block(self, a, d):
        self.b[a:a + len(d)] = d


class _Cpu:
    def __init__(self):
        self.regs = {9: 0x1000, 15: 0x8000}
        self.pc = None

    def r_reg(self, r):
        return self.regs[r]

    def w_reg(self, r, v):
        self.regs[r] = v

    def w_pc(self, v):
        self.pc = v


class _Wb:
    def __init__(self):
        self.markers, self.bb_pending = {}, False

    def mark(self, name, **_):
        self.markers[name] = True


class _Model:
    def __init__(self):
        self.mem, self.cpu, self.wb = _Mem(), _Cpu(), _Wb()


def _ioreq(m, cmd, flags, offset, length, data=0x2000):
    io = 0x1000
    struct.pack_into(">H", m.mem.b, io + wb_disk.IO_COMMAND, cmd)
    m.mem.b[io + wb_disk.IO_FLAGS] = flags
    m.mem.b[io + wb_disk.IO_ERROR] = 0x55
    for off, v in ((wb_disk.IO_OFFSET, offset), (wb_disk.IO_LENGTH, length),
                   (wb_disk.IO_DATA, data), (wb_disk.IO_ACTUAL, 0)):
        m.mem.w32(io + off, v)
    m.mem.w32(0x8000, 0x00FC1234)                # return address on the stack
    return io


def test_hle_quick_read_served_and_returns():
    img = _image()
    m = _Model()
    h = wb_disk.TrackdiskHLE(m, img)
    io = _ioreq(m, wb_disk.CMD_READ, wb_disk.IOF_QUICK, 880 * 512, 1024)
    assert h.trap()
    assert bytes(m.mem.b[0x2000:0x2400]) == img.data[880 * 512:882 * 512]
    assert m.mem.r32(io + wb_disk.IO_ACTUAL) == 1024
    assert m.mem.r8(io + wb_disk.IO_ERROR) == 0
    assert m.cpu.pc == 0xFC1234 and m.cpu.regs[15] == 0x8004   # RTS
    assert h.served == 1 and h.bytes == 1024
    _ioreq(m, wb_disk.CMD_READ, wb_disk.IOF_QUICK, 0, 1024)
    assert h.trap() and m.wb.bb_pending          # boot block read arms detection


@pytest.mark.parametrize("cmd,flags", [(wb_disk.CMD_READ, 0), (3, wb_disk.IOF_QUICK),
                                       (wb_disk.ETD_READ, 0)])
def test_hle_passes_other_requests(cmd, flags):
    m = _Model()
    h = wb_disk.TrackdiskHLE(m, _image())
    _ioreq(m, cmd, flags, 0, 512)
    assert not h.trap()
    assert m.cpu.pc is None and m.mem.b[0x2000:0x2200] == bytes(512)
    assert sum(h.passed.values()) == 1


# ---- model legs: the real ROM decodes our MFM / takes the HLE path ---------

VENV_PY = Path.home() / ".cache" / "amiga64" / "s3probe-venv" / "bin" / "python"


def _model(tmp_path, *extra):
    if not glob.glob(os.path.expanduser("~/.cache/amiga64/aros/*/aros-rom.bin")):
        pytest.skip("no AROS ROM cache (tools/aros/fetch.sh)")
    if not VENV_PY.exists():
        pytest.skip("no s3probe venv (tools/s3probe/setup_venv.sh)")
    img = tmp_path / "synth.adf"
    img.write_bytes(adf.build_adf(FILES, bootcode=BOOTCODE))
    out = tmp_path / "out"
    subprocess.run([str(VENV_PY), str(ROOT / "tools/s3probe/aros_boot_model.py"),
                    "--adf", str(img), "--seconds", "7", "--snap-every", "100",
                    "--out", str(out), *extra], check=True, capture_output=True)
    return json.loads((out / "boot_report.json").read_text())


def test_model_boots_synthetic_bootblock_through_dma(tmp_path):
    rep = _model(tmp_path)
    wb = rep["wb"]
    assert "bootblock" in wb["markers"]
    assert wb["disk"]["dma_reads"] >= 1 and wb["disk"]["tracks"][0] == 0
    assert wb["markers"]["disk_first_read"]["icount"] < wb["markers"]["bootblock"]["icount"]


def test_model_boots_synthetic_bootblock_through_hle(tmp_path):
    rep = _model(tmp_path, "--td-hle")
    wb = rep["wb"]
    assert "bootblock" in wb["markers"]
    assert wb["disk"]["hle_served"] >= 1 and wb["disk"]["dma_reads"] == 0
