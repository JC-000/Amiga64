; fixtures/mod/ui/ui.s - W15-U: the MOD player's UI kit and player screen.
;
; 68000, vasm Motorola syntax, vbcc's m68k C ABI (docs/WAVE15_BRIEF.md I-2):
;   void ui_init(void);                       _ui_init
;   void ui_frame(const struct mod_view *v);  _ui_frame (v at 4(sp))
; d0-d1/a0-a1 are scratch; every other register is preserved.
;
; Spec: docs/UI_READABLE.md.  host/ui_preview.py models every pixel this
; file draws (Screen, player_static, player_frame, Ring); the generated
; includes font.i and ui_tab.i come from it.
;
; The display (H3): hires 640x200, 3 planes interleaved per line (plane p
; of line y at UI_PL + 240y + 80p), every design pixel two hires pixels
; wide.  Each 8x8 cell has a fixed pen (the static pen map): a glyph is
; written only to the planes of its pen; the other planes of that cell
; stay zero from ui_init's clear.
;
; ui_frame works in a cycle of UI_CADENCE calls (supervisor ruling 3):
;   phase 0      the epoch kick (if anything was drawn), then the header
;   phase 1-4    channel 0-3: instrument, note, volume, effect, VU bar
;   phase 5..    trail line 0..TRAIL_N-1 (oldest first; the newest row is
;                the bottom line)
; and on every call the trail capture.  A field is drawn only when the
; value it shows changed.  The kick is a 1-word D-only blit into UI_KICK:
; blt.s bumps the pixel epoch (disp_st+105), so disp.s converts again.
;
; Mutants (tests/run_modui.py --mutants): UI_MUT_PAL (label pen $333),
; UI_MUT_PLANE (pen 2 drawn into plane 0), UI_MUT_NOKICK (no epoch kick),
; UI_MUT_FONT1 (font_thin.i: 1-px strokes, generated by the runner).

        xdef    _ui_init
        xdef    _ui_frame

        ifnd    UI_HUNK                 ; (UI_HUNK, W16-X: a chip BSS hunk, at the end)
        ifnd    UI_BASE
UI_BASE         equ     $070000         ; ruling 4: inside W15-U's $040000-$07FFFF
        endif
UI_COP          equ     UI_BASE         ; copper list
UI_KICK         equ     UI_BASE+$100    ; the epoch blit's target word
UI_PL           equ     UI_BASE+$1000   ; planes, 48,000 bytes
        endif
STRIDE          equ     240             ; bytes per line, 3 planes
CROW            equ     8*STRIDE        ; bytes per cell row
        ifnd    UI_CADENCE
UI_CADENCE      equ     12              ; VERTBs per draw cycle (<= 6 kicks/s at 72 Hz)
        endif
        ifnd    TRAIL_N                 ; trail variant A (default)
TRAIL_N         equ     4
TRAIL_PITCH     equ     2               ; cell rows between lines
TRAIL_DIM       equ     0               ; 1: older lines in pen 2
        endif
        ifnd    TRAIL_EVERY
TRAIL_EVERY     equ     2               ; cycles per trail refresh (~3/s at 72 Hz)
        endif
RING            equ     8               ; captured rows kept
RSTR            equ     64              ; ring entry: E_ROW, E_CELLS, E_FMT, E_TXT
E_FMT           equ     13              ; nonzero: E_TXT holds the formatted line
E_TXT           equ     16              ; 2 + 36 bytes: row number, then columns 4-39
PH_TRAIL        equ     5
        if      PH_TRAIL+TRAIL_N>UI_CADENCE
        fail    "UI_CADENCE is too small for the trail"
        endif
VU_COL          equ     22

CUSTOM          equ     $dff000
DMACONR         equ     $002
BLTCON0         equ     $040
BLTCON1         equ     $042
BLTDPT          equ     $054
BLTSIZE         equ     $058
BLTDMOD         equ     $066
COP1LC          equ     $080
COPJMP1         equ     $088
DIWSTRT         equ     $08e
DIWSTOP         equ     $090
DDFSTRT         equ     $092
DDFSTOP         equ     $094
DMACON          equ     $096
BPL1PTH         equ     $0e0
BPLCON0         equ     $100
BPLCON1         equ     $102
BPLCON2         equ     $104
BPL1MOD         equ     $108
BPL2MOD         equ     $10a
COLOR00         equ     $180

; struct mod_view (fixtures/mod/mod_view.h, I-1)
MV_NAME         equ     8
MV_LEN          equ     28
MV_POS          equ     29
MV_PAT          equ     30
MV_ROW          equ     31
MV_SPD          equ     32
MV_BPM          equ     33
MV_FLAGS        equ     34
MV_CH           equ     36              ; struct mod_chan[4], 8 bytes each
CH_INST         equ     2
CH_VOL          equ     3
CH_NOTE         equ     4
CH_FX           equ     5
CH_PAR          equ     6
CH_VU           equ     7
MV_ELAPSED      equ     68

; ui_st: the kit's state.  Shadows hold the value a field shows ($FFFF:
; unknown, so the first cycle draws it).
                rsreset
S_PHASE         rs.w    1
S_DREW          rs.w    1               ; nonzero: drawn since the last kick
S_POS           rs.w    1
S_LEN           rs.w    1
S_PAT           rs.w    1
S_ROW           rs.w    1
S_SPD           rs.w    1
S_BPM           rs.w    1
S_TIME          rs.w    1
S_PLAY          rs.w    1
S_CIA           rs.w    1
S_LOOP          rs.w    1
S_CH            rs.w    4*5             ; per channel: inst note vol fx vu-px
S_LASTPR        rs.w    1               ; position << 8 | row last captured
S_TVAL          rs.w    1               ; nonzero: S_LASTPR is valid
S_THEAD         rs.w    1               ; ring index of the newest row
S_TCNT          rs.w    1               ; rows in the ring
S_TGEN          rs.w    1               ; +1 per capture
S_TBH           rs.w    1               ; head, count, gen at phase PH_TRAIL
S_TBC           rs.w    1
S_TBG           rs.w    1
S_TCYC          rs.w    1               ; cycles to the next trail refresh
S_TLG           rs.w    TRAIL_N         ; gen each trail line was drawn at
S_NOK           rs.w    1               ; nonzero: S_RAWN is the name shown
S_RAWN          rs.b    20              ; the raw name bytes last seen
S_NAME          rs.b    20              ; the bytes the name field shows
S_TSH           rs.b    TRAIL_N*40      ; the bytes each trail line shows
S_BUF           rs.b    40
S_BLANK         rs.b    40              ; spaces: an empty trail line
S_RING          rs.b    RING*RSTR
S_SIZE          rs.b    0

; ---------------------------------------------------------------------------
; void ui_init(void): the display, the static screen, the state
; ---------------------------------------------------------------------------
_ui_init:
        movem.l d2-d7/a2-a6,-(sp)
        lea     CUSTOM,a6
        ; Order matters: copper DMA goes on only after COP1LC is loaded.
        ; With COPEN on and COP1LC unset, every frame would run the copper
        ; from guest $000000 (on our REU fill $FF00,$00FF: MOVE $00FF to
        ; BPLCON0, 4000 times).
        move.w  #$b200,BPLCON0(a6)      ; hires, 3 planes, colour
        move.w  #0,BPLCON1(a6)
        move.w  #0,BPLCON2(a6)
        move.w  #STRIDE-80,BPL1MOD(a6)
        move.w  #STRIDE-80,BPL2MOD(a6)
        move.w  #$2c81,DIWSTRT(a6)      ; 200 lines (R6)
        move.w  #$f4c1,DIWSTOP(a6)
        move.w  #$003c,DDFSTRT(a6)      ; 80 bytes per hires row
        move.w  #$00d4,DDFSTOP(a6)
        lea     ui_pal(pc),a0
        lea     COLOR00(a6),a1
        moveq   #7,d0
.pal    move.w  (a0)+,(a1)+
        dbra    d0,.pal
        lea     UI_COP,a0               ; the copper list: BPL1PT-BPL3PT, end
        move.l  #UI_PL,d1
        move.w  #BPL1PTH,d2
        moveq   #2,d0
.cop    move.w  d2,(a0)+
        swap    d1
        move.w  d1,(a0)+
        addq.w  #2,d2
        move.w  d2,(a0)+
        swap    d1
        move.w  d1,(a0)+
        addq.w  #2,d2
        add.l   #80,d1
        dbra    d0,.cop
        move.l  #$fffffffe,(a0)
        move.l  #UI_COP,COP1LC(a6)
        move.w  #0,COPJMP1(a6)          ; load the PC (copper DMA still off)
        move.w  #$8240,DMACON(a6)       ; SET DMAEN BLTEN
        bsr     bwait                   ; clear the planes: one D-only blit
        move.w  #$0100,BLTCON0(a6)
        move.w  #0,BLTCON1(a6)
        move.l  #UI_PL,BLTDPT(a6)
        move.w  #0,BLTDMOD(a6)
        move.w  #375<<6,BLTSIZE(a6)     ; 375 x 64 words = 48,000 bytes
        bsr     bwait

        lea     ui_st,a5                ; state: zero, then shadows unknown
        move.l  a5,a0
        move.w  #S_SIZE/2-1,d0
.clr    clr.w   (a0)+
        dbra    d0,.clr
        moveq   #-1,d0
        lea     S_POS(a5),a0
        moveq   #S_CH-S_POS-1,d1        ; header shadows (bytes)
.sh     move.b  d0,(a0)+
        dbra    d1,.sh
        moveq   #3,d1
.shc    move.l  d0,(a0)+                ; inst, note
        move.l  d0,(a0)+                ; vol, fx
        clr.w   (a0)+                   ; vu px: the cleared screen shows 0
        dbra    d1,.shc
        lea     S_TLG(a5),a0
        moveq   #TRAIL_N-1,d1
.shl    move.w  d0,(a0)+
        dbra    d1,.shl
        lea     S_NAME(a5),a0           ; text shadows: spaces (blank cells)
        move.w  #20+TRAIL_N*40-1,d1
        moveq   #' ',d0
.shs    move.b  d0,(a0)+
        dbra    d1,.shs
        lea     S_BLANK(a5),a0
        moveq   #39,d1
.shb    move.b  d0,(a0)+
        dbra    d1,.shb

        lea     ui_font,a4
        lea     UI_PL,a2                ; title bar: pen 3 (planes 0, 1)
        moveq   #7,d2
.tb     move.l  a2,a0
        moveq   #-1,d0
        moveq   #19,d1
        bsr     fill
        lea     80(a2),a0
        moveq   #19,d1
        bsr     fill
        lea     STRIDE(a2),a2
        dbra    d2,.tb
        lea     txt_title(pc),a2
        lea     UI_PL+1*2,a3
        moveq   #17,d2
.tt     moveq   #0,d1
        move.b  (a2)+,d1
        move.l  a3,a0
        bsr     glinv3
        addq.l  #2,a3
        dbra    d2,.tt
        moveq   #-1,d0                  ; the rule lines: pen 7, lines 3-4
        lea     UI_PL+9*CROW+3*STRIDE,a0
        moveq   #119,d1
        bsr     fill
        lea     UI_PL+17*CROW+3*STRIDE,a0
        moveq   #119,d1
        bsr     fill
        lea     ui_static(pc),a2        ; labels
.st     move.l  (a2)+,d0
        beq.s   .std
        move.l  d0,a0
        move.l  (a2)+,a3
        move.w  (a2)+,d1
        bsr     pt
        move.l  a2,d0
        addq.l  #1,d0
        and.b   #$fe,d0
        move.l  d0,a2
        bra.s   .st
.std    move.w  #$8380,CUSTOM+DMACON    ; SET DMAEN BPLEN COPEN (never cleared):
                                        ; the copper runs from UI_COP
        st      S_DREW(a5)
        bsr     kick                    ; show the static screen
        movem.l (sp)+,d2-d7/a2-a6
        rts

; ---------------------------------------------------------------------------
; void ui_frame(const struct mod_view *v)
; a6 = v, a5 = ui_st, a4 = ui_font, d6 = nonzero once anything was drawn
; ---------------------------------------------------------------------------
_ui_frame:
        movem.l d2-d7/a2-a6,-(sp)
        move.l  4+44(sp),a6
        lea     ui_st,a5
        lea     ui_font,a4
        moveq   #0,d6
        bsr     capture
        move.w  S_PHASE(a5),d7
        move.w  d7,d0
        addq.w  #1,d0
        cmp.w   #UI_CADENCE,d0
        blo.s   .ph
        moveq   #0,d0
.ph     move.w  d0,S_PHASE(a5)
        tst.w   d7
        bne.s   .n0
        bsr     kick
        bsr     header
        bra.s   .done
.n0     cmp.w   #PH_TRAIL,d7
        bhs.s   .n1
        move.w  d7,d0
        subq.w  #1,d0
        bsr     chan
        bra.s   .done
.n1     sub.w   #PH_TRAIL,d7
        cmp.w   #TRAIL_N,d7
        bhs.s   .done
        move.w  d7,d0
        bsr     tline
.done   tst.w   d6
        beq.s   .x
        move.w  d6,S_DREW(a5)
.x      movem.l (sp)+,d2-d7/a2-a6
        rts

; The epoch kick: a 1-word D-only blit, if anything was drawn since the last.
kick:
        ifnd    UI_MUT_NOKICK
        tst.w   S_DREW(a5)
        beq.s   .x
        clr.w   S_DREW(a5)
        lea     CUSTOM,a0
.b      btst    #6,DMACONR(a0)          ; BBUSY
        bne.s   .b
        move.w  #$0100,BLTCON0(a0)
        move.w  #0,BLTCON1(a0)
        move.l  #UI_KICK,BLTDPT(a0)
        move.w  #0,BLTDMOD(a0)
        move.w  #$0041,BLTSIZE(a0)      ; 1 x 1 word
        endif
.x      rts

bwait:  btst    #6,CUSTOM+DMACONR
        bne.s   bwait
        rts

; The trail capture: a new (position, row) stores the row in the ring.
capture:
        move.b  MV_POS(a6),d0
        lsl.w   #8,d0
        move.b  MV_ROW(a6),d0
        tst.w   S_TVAL(a5)
        beq.s   .new
        cmp.w   S_LASTPR(a5),d0
        beq.s   .x
.new    move.w  d0,S_LASTPR(a5)
        st      S_TVAL(a5)
        move.w  S_THEAD(a5),d0
        addq.w  #1,d0
        and.w   #RING-1,d0
        move.w  d0,S_THEAD(a5)
        lsl.w   #6,d0                   ; * RSTR
        lea     S_RING(a5),a0
        add.w   d0,a0
        move.b  MV_ROW(a6),(a0)+
        lea     MV_CH+CH_NOTE(a6),a1
        moveq   #3,d1
.c      move.b  (a1),(a0)+              ; note
        move.b  1(a1),(a0)+             ; effect
        move.b  2(a1),(a0)+             ; param
        addq.l  #8,a1
        dbra    d1,.c
        clr.b   (a0)                    ; E_FMT: not formatted yet
        cmp.w   #RING,S_TCNT(a5)
        bhs.s   .f
        addq.w  #1,S_TCNT(a5)
.f      addq.w  #1,S_TGEN(a5)
.x      rts

; --- the header (phase 0) ----------------------------------------------------
header:
        lea     pen1(pc),a3
        moveq   #0,d0
        move.b  MV_POS(a6),d0
        lea     S_POS(a5),a2
        lea     UI_PL+4*CROW+5*2,a0
        bsr     num2
        moveq   #0,d0
        move.b  MV_LEN(a6),d0
        lea     S_LEN(a5),a2
        lea     UI_PL+4*CROW+8*2,a0
        bsr     num2
        moveq   #0,d0
        move.b  MV_PAT(a6),d0
        lea     S_PAT(a5),a2
        lea     UI_PL+4*CROW+16*2,a0
        bsr     num2
        moveq   #0,d0
        move.b  MV_ROW(a6),d0
        lea     S_ROW(a5),a2
        lea     UI_PL+4*CROW+24*2,a0
        bsr     num2
        moveq   #0,d0
        move.b  MV_SPD(a6),d0
        lea     S_SPD(a5),a2
        lea     UI_PL+6*CROW+5*2,a0
        bsr     num2
        bsr     bpm
        bsr     time
        bsr     flags
        ; the song name: bytes up to the first NUL, then spaces
        tst.w   S_NOK(a5)               ; unchanged raw bytes: nothing to do
        beq.s   .nc
        lea     MV_NAME(a6),a1
        lea     S_RAWN(a5),a2
        cmpm.l  (a1)+,(a2)+
        bne.s   .nc
        cmpm.l  (a1)+,(a2)+
        bne.s   .nc
        cmpm.l  (a1)+,(a2)+
        bne.s   .nc
        cmpm.l  (a1)+,(a2)+
        bne.s   .nc
        cmpm.l  (a1)+,(a2)+
        bne.s   .nc
        rts
.nc     st      S_NOK(a5)
        lea     MV_NAME(a6),a1
        lea     S_RAWN(a5),a2
        move.l  (a1)+,(a2)+
        move.l  (a1)+,(a2)+
        move.l  (a1)+,(a2)+
        move.l  (a1)+,(a2)+
        move.l  (a1)+,(a2)+
        lea     S_RAWN(a5),a1
        lea     S_BUF(a5),a2
        moveq   #19,d1
.nl     move.b  (a1)+,d0
        beq.s   .nz
        move.b  d0,(a2)+
        dbra    d1,.nl
        bra.s   .nd
.nz     moveq   #' ',d0
.nzl    move.b  d0,(a2)+
        dbra    d1,.nzl
.nd     lea     S_BUF(a5),a2
        move.w  #S_NAME-S_BUF,d5
        lea     UI_PL+2*CROW+6*2,a0
        moveq   #4,d1
        bra     dd4

; num2: d0.w a value, a2 its shadow, a0 the cell, a3 the pen: "00".."99"
num2:   cmp.w   #99,d0
        bls.s   .c
        moveq   #99,d0
.c      cmp.w   (a2),d0
        beq.s   .x
        move.w  d0,(a2)
        bra     dec2f
.x      rts

; dec2f: d0.w 0-99 as two digits at a0, pen a3
dec2f:  lea     ui_dec2,a2
        add.w   d0,d0
        add.w   d0,a2
        moveq   #1,d1
        bra     pt

bpm:    moveq   #0,d0
        move.b  MV_BPM(a6),d0
        cmp.w   S_BPM(a5),d0
        beq.s   .x
        move.w  d0,S_BPM(a5)
        lea     S_BUF(a5),a2
        divu    #100,d0                 ; d0 = remainder : hundreds
        moveq   #' ',d1
        tst.w   d0
        beq.s   .h
        moveq   #'0',d1
        add.b   d0,d1
.h      move.b  d1,(a2)
        clr.w   d0
        swap    d0
        divu    #10,d0                  ; d0 = ones : tens
        moveq   #' ',d1
        tst.w   d0
        bne.s   .t
        cmp.b   #' ',(a2)
        beq.s   .t2
.t      moveq   #'0',d1
        add.b   d0,d1
.t2     move.b  d1,1(a2)
        swap    d0
        add.b   #'0',d0
        move.b  d0,2(a2)
        lea     UI_PL+6*CROW+16*2,a0
        moveq   #2,d1
        bra     pt
.x      rts

time:   move.l  MV_ELAPSED(a6),d0       ; 1/50 s -> seconds, at most 99:59
        cmp.l   #300000,d0
        blo.s   .d
        move.w  #5999,d0
        bra.s   .c
.d      divu    #50,d0
.c      cmp.w   S_TIME(a5),d0
        beq.s   .x
        move.w  d0,S_TIME(a5)
        and.l   #$ffff,d0
        divu    #60,d0                  ; d0 = ss : mm
        move.l  d0,d2
        lea     UI_PL+4*CROW+34*2,a0
        bsr     dec2f
        swap    d2
        move.w  d2,d0
        lea     UI_PL+4*CROW+37*2,a0
        bra     dec2f
.x      rts

flags:  moveq   #0,d2
        move.b  MV_FLAGS(a6),d2
        move.w  d2,d0                   ; play / stop glyph on the title bar
        and.w   #1,d0
        cmp.w   S_PLAY(a5),d0
        beq.s   .p
        move.w  d0,S_PLAY(a5)
        move.w  #$81,d1
        sub.w   d0,d1
        lea     UI_PL+36*2,a0
        bsr     glinv3
        moveq   #-1,d6
.p      move.w  d2,d0                   ; the timer source
        and.w   #4,d0
        cmp.w   S_CIA(a5),d0
        beq.s   .c
        move.w  d0,S_CIA(a5)
        lea     txt_vbl(pc),a2
        tst.w   d0
        beq.s   .v
        lea     txt_cia(pc),a2
.v      lea     UI_PL+6*CROW+24*2,a0
        moveq   #2,d1
        bsr     pt
.c      move.w  d2,d0                   ; looped
        and.w   #2,d0
        cmp.w   S_LOOP(a5),d0
        beq.s   .x
        move.w  d0,S_LOOP(a5)
        lea     txt_sp4(pc),a2
        tst.w   d0
        beq.s   .l
        lea     txt_loop(pc),a2
.l      lea     UI_PL+6*CROW+29*2,a0
        moveq   #3,d1
        bra     pt
.x      rts

; --- a channel strip (phases 1-4): d0 = channel ------------------------------
chan:   move.w  d0,d7
        move.w  d0,d4
        mulu    #10,d4
        add.w   #S_CH,d4                ; d4 = the channel's shadows in ui_st
        lsl.w   #3,d0
        lea     MV_CH(a6,d0.w),a6       ; a6 = the channel's mod_chan
        move.w  d7,d3
        mulu    #2*CROW,d3
        add.l   #UI_PL+10*CROW,d3       ; d3 = the strip's cell row
        lea     pen1(pc),a3
        moveq   #0,d0                   ; instrument: "--" for none
        move.b  CH_INST(a6),d0
        bne.s   .i1
        moveq   #100,d0
        bra.s   .i2
.i1     cmp.w   #99,d0
        bls.s   .i2
        moveq   #99,d0
.i2     lea     0(a5,d4.w),a2
        cmp.w   (a2),d0
        beq.s   .ni
        move.w  d0,(a2)
        move.l  d3,a0
        addq.l  #4*2,a0
        cmp.w   #100,d0
        bne.s   .id
        lea     txt_dash(pc),a2
        moveq   #1,d1
        bsr     pt
        bra.s   .ni
.id     bsr     dec2f
.ni     moveq   #0,d0                   ; note: "---" outside 0-35
        move.b  CH_NOTE(a6),d0
        cmp.w   #35,d0
        bls.s   .n1
        moveq   #36,d0
.n1     lea     2(a5,d4.w),a2
        cmp.w   (a2),d0
        beq.s   .nn
        move.w  d0,(a2)
        lea     ui_notes,a2
        move.w  d0,d1
        add.w   d0,d0
        add.w   d1,d0
        add.w   d0,a2
        move.l  d3,a0
        lea     8*2(a0),a0
        moveq   #2,d1
        bsr     pt
.nn     moveq   #0,d0                   ; volume, at most 64
        move.b  CH_VOL(a6),d0
        cmp.w   #64,d0
        bls.s   .v1
        moveq   #64,d0
.v1     lea     4(a5,d4.w),a2
        cmp.w   (a2),d0
        beq.s   .nv
        move.w  d0,(a2)
        move.l  d3,a0
        lea     13*2(a0),a0
        bsr     dec2f
.nv     moveq   #0,d0                   ; effect: "---" for 000, '?' above F
        move.b  CH_FX(a6),d0
        cmp.w   #16,d0
        bls.s   .e1
        moveq   #16,d0                  ; shown as '?': shadows stay below $FFFF
.e1     lsl.w   #8,d0
        move.b  CH_PAR(a6),d0
        lea     6(a5,d4.w),a2
        cmp.w   (a2),d0
        beq.s   .nf
        move.w  d0,(a2)
        move.l  d3,a0
        lea     17*2(a0),a0
        tst.w   d0
        bne.s   .f1
        lea     txt_dash(pc),a2
        moveq   #2,d1
        bsr     pt
        bra.s   .nf
.f1     lea     S_BUF(a5),a2
        lea     ui_hex,a1
        move.w  d0,d1
        lsr.w   #8,d1                   ; 0-15, or 16: ui_hex+16 = '?'
        move.b  0(a1,d1.w),(a2)
        move.w  d0,d1
        lsr.w   #4,d1
        and.w   #15,d1
        move.b  0(a1,d1.w),1(a2)
        and.w   #15,d0
        move.b  0(a1,d0.w),2(a2)
        moveq   #2,d1
        bsr     pt
.nf     moveq   #0,d2                   ; the VU bar: 2 px per unit, 0-128 px
        move.b  CH_VU(a6),d2
        cmp.w   #64,d2
        bls.s   .u1
        moveq   #64,d2
.u1     add.w   d2,d2
        lea     8(a5,d4.w),a2
        move.w  (a2),d5
        cmp.w   d5,d2
        beq.s   .x
        move.w  d2,(a2)
        move.w  d2,d0                   ; the cells between the old end and the new
        move.w  d5,d1
        cmp.w   d1,d0
        bls.s   .m
        exg     d0,d1
.m      lsr.w   #3,d0                   ; first cell: min >> 3
        subq.w  #1,d1
        lsr.w   #3,d1                   ; last: (max - 1) >> 3
        move.w  d0,d7
        move.l  d3,a0
        lea     VU_COL*2(a0),a0
        add.w   d7,a0
        add.w   d7,a0
.vl     move.w  d7,d0                   ; on = clamp(L - 8i, 0, 8)
        lsl.w   #3,d0
        neg.w   d0
        add.w   d2,d0
        bpl.s   .p
        moveq   #0,d0
.p      cmp.w   #8,d0
        bls.s   .q
        moveq   #8,d0
.q      add.w   d0,d0
        lea     ui_vupat,a1
        move.w  0(a1,d0.w),d0
        move.w  d7,d5
        lsl.w   #2,d5
        lea     vutab(pc),a1
        move.l  0(a1,d5.w),a1
        jsr     (a1)
        addq.l  #2,a0
        addq.w  #1,d7
        cmp.w   d1,d7
        bls.s   .vl
        moveq   #-1,d6
.x      rts

; --- a trail line (phases PH_TRAIL..): d0 = line, 0 = the oldest ------------
tline:  move.w  d0,d7
        bne.s   .s
        subq.w  #1,S_TCYC(a5)           ; one snapshot per TRAIL_EVERY cycles
        bpl.s   .s
        move.w  #TRAIL_EVERY-1,S_TCYC(a5)
        move.w  S_THEAD(a5),S_TBH(a5)
        move.w  S_TCNT(a5),S_TBC(a5)
        move.w  S_TGEN(a5),S_TBG(a5)
.s      move.w  d7,d0
        add.w   d0,d0
        lea     S_TLG(a5),a2
        add.w   d0,a2
        move.w  S_TBG(a5),d0
        cmp.w   (a2),d0
        beq     .x
        move.w  d0,(a2)
        moveq   #TRAIL_N-1,d2
        sub.w   d7,d2                   ; d2 = age: 0 = the newest row
        lea     S_BLANK(a5),a2
        cmp.w   S_TBC(a5),d2
        bhs.s   .draw
        move.w  S_TBH(a5),d0            ; a6 = the ring entry
        sub.w   d2,d0
        and.w   #RING-1,d0
        lsl.w   #6,d0
        lea     S_RING(a5),a6
        add.w   d0,a6
        tst.b   E_FMT(a6)
        bne.s   .fmtd
        bsr     fmt                     ; once per entry (it scrolls up the lines)
.fmtd   lea     E_TXT(a6),a2
.draw   move.w  d7,d0                   ; d5 = this line's shadow - the text
        mulu    #40,d0
        lea     S_TSH(a5),a1
        add.w   d0,a1
        move.l  a1,d5
        sub.l   a2,d5
        move.w  d7,d0
        lsl.w   #2,d0
        lea     trowtab(pc),a0
        move.l  0(a0,d0.w),a0
        addq.l  #1*2,a0                 ; column 1: the row number, pen 2
        lea     pen2(pc),a3
        moveq   #1,d1
        bsr     dd
        addq.l  #1*2,a0                 ; column 4: the notes
        lea     pen1(pc),a3
        if      TRAIL_DIM
        tst.w   d2
        beq.s   .pn
        lea     pen2(pc),a3
.pn
        endif
        moveq   #8,d1                   ; 36 columns, 9 longs
        bra     dd4
.x      rts

; fmt: the text of ring entry a6 into E_TXT(a6): "rr", then per channel
; "C-2 C20" (blank effect for 000) and two spaces
fmt:    lea     E_TXT(a6),a2
        lea     1(a6),a1
        moveq   #0,d0                   ; the row number
        move.b  (a6),d0
        cmp.w   #99,d0
        bls.s   .r
        moveq   #99,d0
.r      add.w   d0,d0
        lea     ui_dec2,a0
        move.b  0(a0,d0.w),(a2)+
        move.b  1(a0,d0.w),(a2)+
        moveq   #3,d3
.ch     moveq   #0,d0
        move.b  (a1)+,d0
        cmp.w   #35,d0
        bls.s   .n
        moveq   #36,d0
.n      move.w  d0,d1
        add.w   d0,d0
        add.w   d1,d0
        lea     ui_notes,a0
        add.w   d0,a0
        move.b  (a0)+,(a2)+
        move.b  (a0)+,(a2)+
        move.b  (a0)+,(a2)+
        move.b  #' ',(a2)+
        moveq   #0,d0
        move.b  (a1)+,d0
        cmp.w   #16,d0
        bls.s   .e
        moveq   #16,d0                  ; above F: '?'
.e      moveq   #0,d1
        move.b  (a1)+,d1
        move.w  d0,d4
        or.w    d1,d4
        bne.s   .fx
        move.b  #' ',(a2)+              ; no effect: blank
        move.b  #' ',(a2)+
        move.b  #' ',(a2)+
        bra.s   .fe
.fx     lea     ui_hex,a0
        move.b  0(a0,d0.w),(a2)+
        move.w  d1,d0
        lsr.w   #4,d0
        move.b  0(a0,d0.w),(a2)+
        and.w   #15,d1
        move.b  0(a0,d1.w),(a2)+
.fe     move.b  #' ',(a2)+
        move.b  #' ',(a2)+
        dbra    d3,.ch
        st      E_FMT(a6)
        rts

; --- drawing primitives -------------------------------------------------------
; pt: d1+1 glyph bytes from (a2)+ to the cells from a0, pen routine a3
pt:     moveq   #0,d0
        move.b  (a2)+,d0
        lsl.w   #4,d0
        lea     0(a4,d0.w),a1
        jsr     (a3)
        addq.l  #2,a0
        dbra    d1,pt
        moveq   #-1,d6
        rts

; dd: as pt, but only the bytes that differ from the shadow at (a2 + d5)
dd:     moveq   #0,d0
        move.b  (a2),d0
        cmp.b   0(a2,d5.w),d0
        beq.s   .s
        move.b  d0,0(a2,d5.w)
        lsl.w   #4,d0
        lea     0(a4,d0.w),a1
        jsr     (a3)
        moveq   #-1,d6
.s      addq.l  #1,a2
        addq.l  #2,a0
        dbra    d1,dd
        rts

; dd4: as dd for d1+1 longs (4 bytes each): a long equal to its shadow is
; skipped in one compare
dd4:    move.l  (a2),d0
        cmp.l   0(a2,d5.w),d0
        bne.s   .d
        addq.l  #4,a2
        addq.l  #8,a0
        dbra    d1,dd4
        rts
.d      move.w  d1,-(sp)
        moveq   #3,d1
        bsr     dd
        move.w  (sp)+,d1
        dbra    d1,dd4
        rts

; glinv3: glyph byte d1 inverse in pen 3 (planes 0 and 1) at a0
glinv3: and.w   #$ff,d1
        lsl.w   #4,d1
        lea     0(a4,d1.w),a1
        moveq   #7,d1
.l      move.w  (a1)+,d0
        not.w   d0
        move.w  d0,(a0)
        move.w  d0,80(a0)
        lea     STRIDE(a0),a0
        dbra    d1,.l
        rts

; fill: d1+1 longs of d0 from a0
fill:   move.l  d0,(a0)+
        dbra    d1,fill
        rts

